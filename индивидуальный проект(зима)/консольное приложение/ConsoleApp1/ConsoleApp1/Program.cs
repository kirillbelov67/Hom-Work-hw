using System;
using System.Collections.Generic;
using System.IO;

// Программа‑бот для учёта заявок в техподдержку
class Bot
{
    // Список заявок в оперативной памяти (сокращение: t = tickets)
    static List<string> t = new List<string>();
    // Файл для сохранения заявок между запусками (сокращение: f = file)
    static string f = "t.txt";

    // Главная функция - старт программы
    static void Main()
    {
        // Загружаем старые заявки из файла, если он существует
        if (File.Exists(f)) t.AddRange(File.ReadAllLines(f));

        // Здесь мы явно показываем пользователю, какие команды доступны
        Console.WriteLine("Доступные команды:");
        Console.WriteLine("  новая  — создать новую заявку");
        Console.WriteLine("  список — показать все заявки");
        Console.WriteLine("  выход  — сохранить и выйти");
        Console.WriteLine(); // пустая строка для читаемости

        // Бесконечный цикл обработки команд
        while (true)
        {
            Console.Write("> "); // приглашение к вводу
            string c = Console.ReadLine()?.Trim().ToLower() ?? ""; // считываем и нормализуем команду

            // Команда  «новая»
            // Назначение: создать новую заявку
            // Как использовать: ввести «новая», затем в появившемся поле — описание проблемы
            // Что происходит:
            //   - запрашивается описание
            //   - проверяется, что оно не пустое
            //   - формируется запись «время — описание» и добавляется в список
            //   - выводится подтверждение «Создано!»
            if (c == "новая")
            {
                Console.Write("Описание: ");
                string d = Console.ReadLine()?.Trim() ?? "";
                if (!string.IsNullOrEmpty(d))
                {
                    t.Add($"{DateTime.Now:HH:mm} — {d}");
                    Console.WriteLine("Создано!\n");
                }
            }
            // Команда «список»
            // Назначение: показать все сохранённые заявки
            // Как использовать: ввести «список»
            // Что происходит:
            //   - если заявок нет — выводится «Нет заявок»
            //   - если заявки есть — выводится «Заявки:», затем каждая заявка на отдельной строке
            else if (c == "список")
            {
                Console.WriteLine(t.Count == 0 ? "Нет заявок\n" : "Заявки:\n" + string.Join("\n", t) + "\n");
            }
            // Команда «выход»
            // Назначение: завершить работу бота с сохранением данных
            // Как использовать: ввести «выход»
            // Что происходит:
            //   - все заявки из списка t сохраняются в файл t.txt
            //   - выводится сообщение «Пока!»
            //   - программа завершается (return)
            else if (c == "выход")
            {
                File.WriteAllLines(f, t);
                Console.WriteLine("Пока!");
                return;
            }
            // Ообработка неизвестных команд
            // Если введённый текст не совпадает ни с одной из ожидаемых команд,
            // выводится сообщение об ошибке и цикл продолжается
            else
            {
                Console.WriteLine("Неизвестная команда. Введите 'новая', 'список' или 'выход'\n");
            }
        }
    }
}